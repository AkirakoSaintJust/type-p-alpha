"""Generate a build-tree prototype of the engine with an additive oscillator.

The product engine is copied, not modified. Each operator's `p1_wave` read is
replaced by a two-table additive read: a dark and a bright 16-harmonic table, a
mip level chosen from the voice's phase step, and a per-voice morph from the
operator's amplitude envelope. The tables and the replacement live only in the
build tree, so the shipped engine and its manifest stay untouched.
"""

from __future__ import annotations

import argparse
import math
import re
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_LEVELS = 9
_SIZE = 1024
_HARMONICS = 16


def _recipe(harmonics: int, tilt: float, formant: int, peak: float) -> list[float]:
    raw = []
    total = 0.0
    for h in range(1, harmonics + 1):
        value = h ** (-tilt)
        if formant > 0:
            distance = h - formant
            value += peak * math.exp(-distance * distance / 8.0)
        raw.append(value)
        total += value
    scale = 0.95 / total if total > 0.0 else 0.0
    return [value * scale for value in raw]


def _table(amps: list[float], level: int) -> list[int]:
    limit = max(1, _HARMONICS >> level)
    values = []
    for n in range(_SIZE):
        total = 0
        for h in range(1, limit + 1):
            total += int(round(amps[h - 1] * 32767.0 *
                               math.sin(2.0 * math.pi * h * n / _SIZE)))
        values.append(max(-32768, min(32767, total)))
    return values


def _emit(name: str, table: list[int]) -> str:
    lines = [f"static const int16_t {name}[{_LEVELS * _SIZE}] = {{"]
    for start in range(0, len(table), 16):
        chunk = ", ".join(str(value) for value in table[start:start + 16])
        lines.append("    " + chunk + ",")
    lines.append("};")
    return "\n".join(lines)


def _header() -> str:
    dark = _recipe(_HARMONICS, 2.2, 0, 0.0)
    bright = _recipe(_HARMONICS, 0.7, 6, 1.2)
    dark_tables = []
    bright_tables = []
    for level in range(_LEVELS):
        dark_tables.extend(_table(dark, level))
        bright_tables.extend(_table(bright, level))
    return f"""/* SPDX-License-Identifier: GPL-3.0-only
 * Copyright (C) 2026 P1Onken
 * GENERATED by plugin/tools/additive_prototype.py, build tree only.
 * Two 16-harmonic additive tables, nine mip levels each, Q15.
 */
#pragma once
#include <stdint.h>

#define P1_ADDITIVE_LEVELS {_LEVELS}
#define P1_ADDITIVE_SIZE {_SIZE}

{_emit('p1_additive_dark', dark_tables)}

{_emit('p1_additive_bright', bright_tables)}

static inline uint32_t p1_additive_mip(uint32_t step, uint32_t harmonics,
                                       uint32_t levels)
{{
    uint32_t mip = 0u;
    while (mip + 1u < levels &&
           (uint64_t)(harmonics >> mip) * step > 0x40000000ull)
        ++mip;
    return mip;
}}

static inline int32_t p1_additive_wave(uint32_t phase, uint32_t mip,
                                       int32_t morph)
{{
    if (mip >= P1_ADDITIVE_LEVELS)
        mip = P1_ADDITIVE_LEVELS - 1u;
    const uint32_t index = (phase >> 22) & (P1_ADDITIVE_SIZE - 1u);
    const int32_t mix = morph < 0 ? 0 : (morph > 32767 ? 32767 : morph);
    const int32_t a =
        p1_additive_dark[mip * P1_ADDITIVE_SIZE + index];
    const int32_t b =
        p1_additive_bright[mip * P1_ADDITIVE_SIZE + index];
    return (a * (32768 - mix) + b * mix) >> 15;
}}
"""


def _patch(source: str) -> str:
    pattern = re.compile(
        r"int32_t (op([1-4])_osc_audio_x) = p1_wave\[op\2_osc_base\[v\]\s*\n"
        r"\s*\+ \(\(op\2_osc_bl\[v\] \? op\2_ph_mip_x : 0u\) << 10\) "
        r"\+ \(op\2_ph_phase_x >> 22\)\];"
    )

    def replace(match: re.Match[str]) -> str:
        op = match.group(2)
        return (
            f"int32_t op{op}_osc_audio_x = p1_additive_wave("
            f"op{op}_ph_phase_x, "
            f"p1_additive_mip(op{op}_ph_step[v], {_HARMONICS}u, "
            f"{_LEVELS}u), p1_additive_morph);"
        )

    patched, count = pattern.subn(replace, source)
    if count != 4:
        raise SystemExit(f"additive prototype: replaced {count} oscillators, expected 4")
    if '#include "tables.h"' in patched:
        patched = patched.replace(
            '#include "tables.h"',
            '#include "tables.h"\n#include "additive_tables.h"\n\n'
            "int32_t p1_additive_morph = 0;\n"
            "int32_t p1_additive_morph_step = 0;",
            1,
        )
    else:
        raise SystemExit("additive prototype: tables include not found")
    loop = "for (uint32_t f = b; f < b + 32u && f < frames; f++) {"
    if loop not in patched:
        raise SystemExit("additive prototype: sample loop not found")
    patched = patched.replace(
        loop,
        loop + "\n            p1_additive_morph += p1_additive_morph_step;",
        1,
    )
    return patched


def main() -> int:
    parser = argparse.ArgumentParser(prog="additive_prototype")
    parser.add_argument("--engine", type=Path, required=True,
                        help="the product engine/gen directory")
    parser.add_argument("--out", type=Path, required=True,
                        help="the prototype output directory")
    args = parser.parse_args()
    source = (args.engine / "type_p_alpha_dsp.c").read_text(encoding="utf-8")
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "type_p_alpha_dsp.c").write_text(_patch(source), encoding="utf-8")
    (args.out / "additive_tables.h").write_text(_header(), encoding="utf-8")
    print(f"wrote {args.out / 'type_p_alpha_dsp.c'}")
    print(f"wrote {args.out / 'additive_tables.h'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
