"""Generate engine/gen/math_tables.h for the 48 kHz control block.

The sine, exp, log, semitone, cent, detune and level tables do not depend on
the sample rate. The envelope rate coefficients are per 32-sample control
block, so the 44.1 kHz table is transformed to the 48 kHz block period with
`1 - (1 - a)^(44100/48000)`, which keeps the same one-pole time constant in
seconds. The 44.1 table is the musical base, and its values are the ones the
engine used before the rate change.

Run from the repository root: python tools/gen_math_tables.py
"""
from __future__ import annotations

import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "engine" / "gen" / "math_tables.h"
OLD_RATE = 44100.0
NEW_RATE = 48000.0
BLOCK = 32


def q15(x: float) -> int:
    v = int(round(x * 32768.0))
    return max(-32768, min(32767, v))


def q16(x: float) -> int:
    v = int(round(x * 65536.0))
    return max(-2147483648, min(2147483647, v))


def c_array(ctype: str, name: str, values: list[int], width: int) -> list[str]:
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    row: list[str] = []
    for value in values:
        row.append(f"{value:>6d}")
        if len(row) == width:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return lines


def rate_base() -> list[int]:
    return [
        min(65536, max(0, round(65536.0 * 2.0 ** (-((99 - r) ** 0.5) / 0.75))))
        for r in range(100)
    ]


def rate_r3_base() -> list[int]:
    return [2, 3] + [
        min(65536, max(1, round(4.0 * (16384.0 ** ((r - 2) / 97.0)))))
        for r in range(2, 100)
    ]


def keep_time(coefficient: int, old_rate: float, new_rate: float) -> int:
    """Transform a Q16 per-block coefficient to the new block period."""
    alpha = min(1.0, max(0.0, coefficient / 65536.0))
    beta = 1.0 - (1.0 - alpha) ** (old_rate / new_rate)
    return max(0, min(65536, int(round(beta * 65536.0))))


def build(rate: float) -> dict[str, list[int]]:
    n = 256
    sin_q15 = [q15(math.sin(math.pi / 2.0 * i / n)) for i in range(n)]
    exp2_q16 = [q16(2.0 ** (-i / n)) for i in range(n)]
    log2_q16 = [q16(math.log2(1.0 + i / n)) for i in range(n)]
    semi_q16 = [q16(2.0 ** (i / 12.0)) for i in range(12)]
    cent_q16 = [q16(2.0 ** (i / 1200.0)) for i in range(100)]
    detune_pitch = [
        round(32768.0 * (2.0 ** (d / 1200.0) - 1.0)) for d in range(-50, 51)
    ]
    rate_coeff = [keep_time(a, OLD_RATE, rate) for a in rate_base()]
    rate_coeff_r3 = [keep_time(a, OLD_RATE, rate) for a in rate_r3_base()]
    level_gain = [0] + [
        max(1, min(32767, round(32767.0 * 10.0 ** (-(99 - l) * 0.75 / 20.0))))
        for l in range(1, 100)
    ]
    return {
        "sin_q15": sin_q15,
        "exp2_q16": exp2_q16,
        "log2_q16": log2_q16,
        "semi_q16": semi_q16,
        "cent_q16": cent_q16,
        "detune_pitch": detune_pitch,
        "rate_coeff": rate_coeff,
        "rate_coeff_r3": rate_coeff_r3,
        "level_gain": level_gain,
    }


def render(rate: float) -> str:
    tables = build(rate)
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * Copyright (C) 2026 P1Onken",
        " * GENERATED by tools/gen_math_tables.py, do not edit by hand.",
        f" * const fixed-point tables for the {int(rate)} Hz core, "
        f"{BLOCK}-sample control block. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    lines += c_array("int16_t", "p1_sin_q15", tables["sin_q15"], 16)
    lines += [""]
    lines += c_array("int32_t", "p1_exp2_q16", tables["exp2_q16"], 8)
    lines += [""]
    lines += c_array("int32_t", "p1_log2_q16", tables["log2_q16"], 8)
    lines += [""]
    lines += c_array("int32_t", "p1_semi_q16", tables["semi_q16"], 8)
    lines += [""]
    lines += c_array("int32_t", "p1_cent_q16", tables["cent_q16"], 8)
    lines += [""]
    lines += c_array("int32_t", "p1_detune_pitch", tables["detune_pitch"], 8)
    lines += [""]
    lines += c_array("int32_t", "p1_rate_coeff", tables["rate_coeff"], 8)
    lines += [""]
    lines += c_array("int32_t", "p1_rate_coeff_r3", tables["rate_coeff_r3"], 8)
    lines += [""]
    lines += c_array("int32_t", "p1_level_gain", tables["level_gain"], 8)
    lines += [""]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rate", type=float, default=NEW_RATE)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(args.rate), encoding="utf-8")
    print(f"wrote {args.out} at {args.rate:.0f} Hz ({BLOCK}-sample block)")


if __name__ == "__main__":
    main()
